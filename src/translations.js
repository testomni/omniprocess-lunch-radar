export function getRestaurantName(restaurant, text) {
  const placeholderNumber = /^placeholder-restaurant-(\d+)$/.exec(restaurant.id)?.[1];
  return placeholderNumber
    ? `${text.placeholderRestaurant} ${placeholderNumber}`
    : restaurant.name;
}

export function getCuisineName(cuisine, text) {
  const placeholderNumber = /^Platshållarkök (\d+)$/.exec(cuisine)?.[1];
  return placeholderNumber
    ? `${text.placeholderCuisine} ${placeholderNumber}`
    : text.cuisines[cuisine] ?? cuisine;
}